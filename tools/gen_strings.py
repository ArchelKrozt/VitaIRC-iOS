#!/usr/bin/env python3
"""Generates Sources/VitaIRCCore/L.swift: Spanish UI text -> English.

The table is tools/strings_vita.py (texts shared with VitaIRC for PS Vita),
tools/strings_phone.py (shared with VitaIRC for Android) and tools/strings_ios.py."""
import os
here = os.path.dirname(os.path.abspath(__file__))
table = {}
for name in ('strings_vita.py', 'strings_phone.py', 'strings_ios.py'):
    ns = {}
    exec(open(os.path.join(here, name), encoding='utf-8').read(), ns)
    table.update(ns['T'])

def sw(s):   # the table holds C string contents: \" and \\ work the same in Swift
    assert '\\(' not in s, s
    return '"' + s + '"'

out = ['// Generated by tools/gen_strings.py: Spanish source strings -> English. Do not edit.',
       'import Foundation', '',
       'public enum L {',
       '    nonisolated(unsafe) public static var english = false',
       '    public static func t(_ es: String) -> String { english ? (en[es] ?? es) : es }',
       '    private static let en: [String: String] = {',
       '        var d = [String: String](minimumCapacity: %d)' % (len(table) * 2)]
for k, v in table.items():
    out.append('        d[%s] = %s' % (sw(k), sw(v)))
out += ['        return d', '    }()', '}', '',
        '/// Shorthand used everywhere: t("texto en español")',
        'public func t(_ es: String) -> String { L.t(es) }', '']
dst = os.path.join(here, '..', 'Sources', 'VitaIRCCore', 'L.swift')
open(dst, 'w', encoding='utf-8').write('\n'.join(out))
print(len(table), 'strings')
